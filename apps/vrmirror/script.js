function applyLang(lang) {
  const t = translations[lang] || translations['en'];
  const en = translations['en'];
  const pick = k => (t[k] !== undefined ? t[k] : en[k]); // fallback a inglés

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = pick(el.getAttribute('data-i18n'));
    if (v !== undefined) el.textContent = v;
  });

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.style.fontFamily = lang === 'ar'
    ? "'Cairo', sans-serif"
    : "'Inter', -apple-system, sans-serif";
}

function changeLanguage() {
  const sel = document.getElementById('lang-selector');
  if (sel) applyLang(sel.value);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-year]').forEach(el => { el.textContent = new Date().getFullYear(); });

  const sel = document.getElementById('lang-selector');
  const nav = (navigator.language || navigator.userLanguage || 'es').slice(0, 2);
  const lang = translations[nav] ? nav : 'es';
  if (sel) { sel.value = lang; sel.addEventListener('change', changeLanguage); }
  applyLang(lang);
});
