document.addEventListener('DOMContentLoaded', () => {
  // Current year in footer
  document.querySelectorAll('[data-year]').forEach(el => { el.textContent = new Date().getFullYear(); });

  const langSelector = document.getElementById('lang-selector');
  const userLang = (navigator.language || navigator.userLanguage || 'en').split('-')[0];
  let currentLang = translations[userLang] ? userLang : 'en';

  if (langSelector) {
    langSelector.value = currentLang;
    langSelector.addEventListener('change', e => setLanguage(e.target.value));
  }
  setLanguage(currentLang);
});

function setLanguage(lang) {
  const t = translations[lang] || translations['en'];
  const en = translations['en'];
  const pick = key => (t[key] !== undefined ? t[key] : en[key]); // fall back to English

  // Simple text nodes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = pick(el.getAttribute('data-i18n'));
    if (v !== undefined) el.textContent = v;
  });

  // HTML nodes (for rich content like <a> tags inside)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = pick(el.getAttribute('data-i18n-html'));
    if (v !== undefined) el.innerHTML = v;
  });

  // RTL for Arabic
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  document.body.style.fontFamily = lang === 'ar'
    ? "'Cairo', sans-serif"
    : "'Inter', -apple-system, sans-serif";
}
